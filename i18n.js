  const HTML_LANG = { en: 'en', de: 'de', gsw: 'gsw-CH', fr: 'fr', es: 'es', pt: 'pt-PT', th: 'th', ja: 'ja', zh: 'zh-Hans', ko: 'ko' };

  function pick() {
    try {
      const saved = localStorage.getItem('lang');
      if (saved && S[saved]) return saved;
    } catch (e) {}
    const nav = (navigator.languages || [navigator.language || 'en']);
    for (const l of nav) {
      const low = l.toLowerCase();
      if (low.startsWith('gsw')) return 'gsw';
      if (low.startsWith('de')) return 'de';
      if (low.startsWith('fr')) return 'fr';
      if (low.startsWith('es')) return 'es';
      if (low.startsWith('pt')) return 'pt';
      if (low.startsWith('th')) return 'th';
      if (low.startsWith('ja')) return 'ja';
      if (low.startsWith('zh')) return 'zh';
      if (low.startsWith('ko')) return 'ko';
      if (low.startsWith('en')) return 'en';
    }
    return 'en';
  }

  let current = 'en';

  function apply(lang) {
    if (!S[lang]) lang = 'en';
    current = lang;
    const dict = S[lang], fallback = S.en;
    document.documentElement.lang = HTML_LANG[lang] || lang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      const val = dict[key] !== undefined ? dict[key] : fallback[key];
      if (val !== undefined) el.innerHTML = val;
    });
    try { localStorage.setItem('lang', lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  }

